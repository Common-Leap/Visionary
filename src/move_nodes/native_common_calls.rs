use super::{signature, Signature};

// Exact no-argument common methods declared by the native lua2cpp bindings.
// Dump method-pointer syntax is normalized to these explicit SDK calls.
macro_rules! common_calls {
    ($($class:ident => [$($method:ident),* $(,)?]),* $(,)?) => {
        pub(super) const SIGNATURES: &[Signature] = &[
            $($(signature(
                concat!("smash::lua2cpp::", stringify!($class), "_", stringify!($method)),
                stringify!($method),
                concat!("agent as *mut L2CAgentBase as *mut smash::lua2cpp::", stringify!($class)),
                &[],
            ),)*)*
        ];
    };
}

