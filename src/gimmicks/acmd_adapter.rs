//! Render Visionary's verified ACMD source into the selected gimmick runtime.
//!
//! The ordinary exporter builds a complete standalone Skyline crate. A mod
//! package has one `plugin.nro`, though, so a gimmick runtime cannot coexist
//! with that crate as a second artifact. This adapter consumes only the exact
//! generated `src/<fighter>/mod.rs` and `src/<fighter>/acmd.rs` layout from
//! [`crate::acmd::ModProject`] and embeds it in the runtime's one reviewed,
//! managed ACMD slot. It never searches for a plugin or accepts arbitrary
//! Rust-path input.

use std::collections::BTreeMap;
use std::fmt;

use crate::acmd::ModProject;

/// Marker in the one generated ACMD source slot Visionary may replace.
pub const GENERATED_ACMD_SLOT_MARKER: &str = "visionary.gimmicks.generated-acmd-slot.v1";

/// Parse-checked Rust source for the runtime's generated ACMD module.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RenderedAcmdAdapter {
    pub source: String,
    pub fighters: Vec<String>,
}

/// A specific, source-derived rejection. Errors are intentionally about the
/// generated project shape rather than a filesystem destination: rendering
/// happens before the selected runtime is mutated.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AcmdAdapterError {
    pub subject: String,
    pub reason: String,
}

impl fmt::Display for AcmdAdapterError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(formatter, "{}: {}", self.subject, self.reason)
    }
}

/// Render a no-op adapter. Packaging it is deliberate: it replaces a prior
/// Visionary-generated ACMD slot so a later gimmick-only export cannot retain
/// old ACMD registrations from an earlier package.
pub fn render_empty() -> RenderedAcmdAdapter {
    RenderedAcmdAdapter {
        source: format!(
            "//! @generated by Visionary's managed ACMD adapter; do not edit.\n\
             const VISIONARY_STATIC_ACMD_ADAPTER_SLOT: &str = \"{GENERATED_ACMD_SLOT_MARKER}\";\n\n\
             /// Install the ACMD registrations included by this package.\n\
             pub fn install() {{}}\n"
        ),
        fighters: Vec::new(),
    }
}

/// Embed a verified standalone generated source project into the selected
/// runtime. `None` is represented by [`render_empty`].
pub fn render(project: Option<&ModProject>) -> Result<RenderedAcmdAdapter, AcmdAdapterError> {
    let Some(project) = project else {
        return Ok(render_empty());
    };

    #[derive(Default)]
    struct FighterFiles {
        mod_file: Option<String>,
        acmd_file: Option<String>,
    }

    let mut fighters: BTreeMap<String, FighterFiles> = BTreeMap::new();
    for file in &project.files {
        let parts = file.rel_path.split('/').collect::<Vec<_>>();
        match parts.as_slice() {
            ["Cargo.toml"]
            | ["README.md"]
            | ["rust-toolchain.toml"]
            | ["info.toml"]
            | ["build.sh"]
            | ["build.bat"]
            | ["src", "lib.rs"] => {}
            ["src", fighter, "mod.rs"] => {
                require_rust_identifier(fighter, &file.rel_path)?;
                let entry = fighters.entry((*fighter).to_string()).or_default();
                if entry.mod_file.replace(file.contents.clone()).is_some() {
                    return Err(shape_error(
                        &file.rel_path,
                        "generated source contains the fighter module more than once",
                    ));
                }
            }
            ["src", fighter, "acmd.rs"] => {
                require_rust_identifier(fighter, &file.rel_path)?;
                let entry = fighters.entry((*fighter).to_string()).or_default();
                if entry.acmd_file.replace(file.contents.clone()).is_some() {
                    return Err(shape_error(
                        &file.rel_path,
                        "generated source contains the fighter ACMD module more than once",
                    ));
                }
            }
            _ => {
                return Err(shape_error(
                    &file.rel_path,
                    "not part of Visionary's reviewed generated ACMD project layout",
                ));
            }
        }
    }

    let mut source = format!(
        "//! @generated by Visionary's managed ACMD adapter; do not edit.\n\
         const VISIONARY_STATIC_ACMD_ADAPTER_SLOT: &str = \"{GENERATED_ACMD_SLOT_MARKER}\";\n\n"
    );
    for (fighter, files) in &fighters {
        let Some(mod_file) = files.mod_file.as_deref() else {
            return Err(shape_error(
                &format!("src/{fighter}"),
                "generated fighter is missing mod.rs",
            ));
        };
        let Some(acmd_file) = files.acmd_file.as_deref() else {
            return Err(shape_error(
                &format!("src/{fighter}"),
                "generated fighter is missing acmd.rs",
            ));
        };
        validate_generated_module(fighter, mod_file, acmd_file)?;
        source.push_str(&format!("mod {fighter} {{\n    mod acmd {{\n"));
        indent(&mut source, acmd_file, 8);
        source.push_str("    }\n\n");
        source.push_str("    pub fn install() {\n");
        source.push_str(&format!(
            "        let agent = &mut smashline::Agent::new({fighter:?});\n"
        ));
        source.push_str("        acmd::install(agent);\n        agent.install();\n    }\n}\n\n");
    }
    source.push_str(
        "/// Install the ACMD registrations included by this package.\npub fn install() {\n",
    );
    for fighter in fighters.keys() {
        source.push_str(&format!("    {fighter}::install();\n"));
    }
    source.push_str("}\n");
    syn::parse_file(&source).map_err(|error| AcmdAdapterError {
        subject: "generated ACMD adapter".to_string(),
        reason: format!("renderer produced unparsable Rust: {error}"),
    })?;
    Ok(RenderedAcmdAdapter {
        source,
        fighters: fighters.into_keys().collect(),
    })
}

fn validate_generated_module(
    fighter: &str,
    mod_file: &str,
    acmd_file: &str,
) -> Result<(), AcmdAdapterError> {
    let expected_install = format!("smashline::Agent::new(\"{fighter}\")");
    if !mod_file.contains("mod acmd;")
        || !mod_file.contains("acmd::install(agent);")
        || !mod_file.contains("agent.install();")
        || !mod_file.contains(&expected_install)
    {
        return Err(shape_error(
            &format!("src/{fighter}/mod.rs"),
            "does not match Visionary's reviewed generated fighter installer",
        ));
    }
    syn::parse_file(acmd_file).map_err(|error| AcmdAdapterError {
        subject: format!("src/{fighter}/acmd.rs"),
        reason: format!("generated ACMD source is not valid Rust: {error}"),
    })?;
    if !acmd_file.contains("pub fn install(agent: &mut smashline::Agent)") {
        return Err(shape_error(
            &format!("src/{fighter}/acmd.rs"),
            "does not expose Visionary's reviewed ACMD installer",
        ));
    }
    Ok(())
}

fn require_rust_identifier(value: &str, subject: &str) -> Result<(), AcmdAdapterError> {
    if syn::parse_str::<syn::Ident>(value).is_ok() {
        Ok(())
    } else {
        Err(shape_error(
            subject,
            "generated fighter module is not a Rust identifier",
        ))
    }
}

fn shape_error(subject: &str, reason: &str) -> AcmdAdapterError {
    AcmdAdapterError {
        subject: subject.to_string(),
        reason: reason.to_string(),
    }
}

fn indent(output: &mut String, input: &str, spaces: usize) {
    let prefix = " ".repeat(spaces);
    for line in input.lines() {
        output.push_str(&prefix);
        output.push_str(line);
        output.push('\n');
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::acmd::{GeneratedFile, ModProject};
    use crate::data::{ExcuteStmt, SoundCall};
    use crate::mod_project::{FighterMod, ModProjectFile, RosterMod};
    use crate::move_nodes::model::{MoveGraph, MoveNode, MoveTrack, NodeKind, Track};

    fn project(files: Vec<(&str, &str)>) -> ModProject {
        ModProject {
            name: "fixture".to_string(),
            files: files
                .into_iter()
                .map(|(rel_path, contents)| GeneratedFile {
                    rel_path: rel_path.to_string(),
                    contents: contents.to_string(),
                })
                .collect(),
        }
    }

    const MOD: &str = "mod acmd;\n\npub fn install() {\n    let agent = &mut smashline::Agent::new(\"cloud\");\n    acmd::install(agent);\n    agent.install();\n}\n";
    const ACMD: &str = "pub fn install(agent: &mut smashline::Agent) {\n    agent.acmd(\"game_attack11\", game_attack11, smashline::Priority::Default);\n}\n\nunsafe extern \"C\" fn game_attack11(_: &mut smash::lua2cpp::L2CAgentBase) {}\n";

    #[test]
    fn embeds_only_the_reviewed_generated_fighter_layout() {
        let artifact = render(Some(&project(vec![
            ("Cargo.toml", "[package]"),
            ("src/lib.rs", "ignored generated entry"),
            ("src/cloud/mod.rs", MOD),
            ("src/cloud/acmd.rs", ACMD),
        ])))
        .unwrap();

        assert_eq!(artifact.fighters, ["cloud"]);
        assert!(artifact.source.contains("mod cloud"));
        assert!(artifact.source.contains("cloud::install();"));
        assert!(artifact.source.contains(GENERATED_ACMD_SLOT_MARKER));
    }

    #[test]
    fn missing_half_of_a_generated_fighter_is_refused() {
        let error = render(Some(&project(vec![("src/cloud/mod.rs", MOD)]))).unwrap_err();
        assert!(error.reason.contains("missing acmd.rs"), "{error}");
    }

    #[test]
    fn arbitrary_generated_source_paths_are_refused() {
        let error = render(Some(&project(vec![("src/other.rs", "fn surprise() {}")]))).unwrap_err();
        assert!(error
            .reason
            .contains("reviewed generated ACMD project layout"));
    }

    #[test]
    fn empty_adapter_replaces_prior_acmd_registrations_with_a_noop() {
        let artifact = render(None).unwrap();
        assert!(artifact.fighters.is_empty());
        assert!(artifact.source.contains("pub fn install() {}"));
    }

    #[test]
    fn static_adapter_preserves_top_level_motion_rate_and_bare_sound_calls() {
        let graph = MoveGraph {
            tracks: vec![
                MoveTrack {
                    track: Track::Game,
                    effect_execute_baseline: Vec::new(),
                    nodes: vec![MoveNode {
                        id: 1,
                        kind: NodeKind::MotionRate { rate: 0.5 },
                    }],
                    baseline: Vec::new(),
                },
                MoveTrack {
                    track: Track::Sound,
                    effect_execute_baseline: Vec::new(),
                    nodes: vec![MoveNode {
                        id: 1 << 29,
                        kind: NodeKind::BareCommand {
                            command: Box::new(ExcuteStmt::Sound(SoundCall {
                                func: "PLAY_SE".into(),
                                sounds: vec!["se_common_swing_01".into()],
                                tail: None,
                            })),
                        },
                    }],
                    baseline: Vec::new(),
                },
            ],
            ..MoveGraph::default()
        };
        let mut fighter = FighterMod::default();
        fighter.move_graphs.insert("attack11".into(), graph);
        let project = ModProjectFile {
            version: crate::mod_project::PROJECT_VERSION,
            name: "adapter-placement".into(),
            fighters: std::collections::HashMap::from([("mario".into(), fighter)]),
            roster: RosterMod::default(),
        };
        let generated = crate::mod_export::source_project(&project)
            .unwrap()
            .expect("the graph produces ACMD source");
        let artifact = render(Some(&generated.project)).unwrap();

        assert!(artifact
            .source
            .contains("macros::FT_MOTION_RATE(agent, 0.5);"));
        assert!(artifact
            .source
            .contains("macros::PLAY_SE(agent, Hash40::new(\"se_common_swing_01\"));"));
        assert!(!artifact.source.contains("AttackHeight"));
        assert!(!artifact.source.contains("AttackDirectionAxis"));
        assert!(
            !artifact.source.contains("if macros::is_excute(agent)"),
            "the static adapter must not wrap top-level calls in an is_excute block"
        );
    }

    #[test]
    fn static_adapter_imports_native_attack_wrapper_types() {
        let script = crate::data::AcmdScript {
            stmts: vec![crate::data::AcmdStmt::Excute(vec![
                ExcuteStmt::AttackModuleSetHeightAll {
                    height: crate::data::AttackHeightAllKind::High,
                    arg3: false,
                },
                ExcuteStmt::AttackModuleSetAttackReferenceJointId {
                    kind: crate::data::AttackReferenceJointKind::TopYZX,
                },
            ])],
        };
        let generated = crate::acmd::build_mod_project(
            &[("cloud".into(), "attack11".into(), script)],
            "adapter_attack_imports",
        );
        let artifact = render(Some(&generated)).unwrap();
        let header = artifact
            .source
            .split("pub fn install(agent")
            .next()
            .unwrap();

        assert!(header.contains("AttackDirectionAxis, AttackHeight"));
        assert_eq!(header.matches("AttackDirectionAxis,").count(), 1);
        assert_eq!(header.matches("AttackHeight}").count(), 1);
        assert!(artifact
            .source
            .contains("AttackHeight(*ATTACK_HEIGHT_HIGH)"));
        assert!(artifact
            .source
            .contains("AttackDirectionAxis(*ATTACK_DIRECTION_Y)"));
    }
}
